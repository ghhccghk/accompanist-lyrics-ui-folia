"""Before/after static-layout snapping against unchanged original Motion frames.

Baseline folders are saved before applying the candidate, never generated by changing
an oracle. Descriptive pixel errors do not replace inspection of original PNGs.
"""
from pathlib import Path
from PIL import Image, ImageChops, ImageDraw, ImageStat
import csv
from collections import defaultdict
from statistics import mean

root = Path(__file__).resolve().parents[1] / 'build/verification'
out = root / 'sampling-full-comparison'; out.mkdir(parents=True, exist_ok=True)
folders = {
    'classic-kotlin': 'classic-manual-upstream',
    'classic-continuous-kotlin': 'classic-continuous-upstream',
    'classic-matrix-kotlin': 'classic-manual-upstream',
    'classic-bidi-kotlin': 'classic-bidi-upstream',
    'classic-interlude-kotlin': 'classic-interlude-upstream',
    'classic-interrupted-kotlin': 'classic-interrupted-upstream',
}
rows = []; summary = defaultdict(lambda: [[], []])
for folder, original in folders.items():
    for old in sorted((root / 'sampling-full-legacy' / folder).glob('*.png')):
        ref = root / original / old.name
        if not ref.exists(): raise FileNotFoundError(ref)
        a = Image.open(ref).convert('RGB')
        candidates = [Image.open(old).convert('RGB'), Image.open(root / folder / old.name).convert('RGB')]
        errors = []
        for b in candidates:
            assert a.size == b.size
            union = Image.new('L', a.size)
            for image in [a, b]:
                for channel in ImageChops.difference(image, Image.new('RGB', image.size, (22,36,53))).split():
                    union = ImageChops.lighter(union, channel)
            mask = union.point(lambda x: 255 if x > 8 else 0)
            errors.append(sum(ImageStat.Stat(ImageChops.difference(a,b),mask).mean) / 3 if mask.getbbox() else 0)
        rows.append((folder, old.name, *errors, errors[1]-errors[0]))
        for i in [0,1]: summary[folder][i].append(errors[i])
        if old.name.endswith('1500ms.png') or old.name in ['150-1241ms.png','default-3400ms.png']:
            w,h = a.size
            sheet = Image.new('RGB',(w*3,h+22),'#eef1f5')
            for i,(label,image) in enumerate(zip(['Original','Before','Layout snapped'],[a,*candidates])):
                sheet.paste(image,(i*w,22)); ImageDraw.Draw(sheet).text((i*w+4,4),label,fill='black')
            sheet.save(out / f'{folder}-{old.name}')
with (out / 'pixel-errors.csv').open('w',newline='') as f:
    writer=csv.writer(f); writer.writerow(['scene_set','frame','before_rgb_mae','after_rgb_mae','delta']); writer.writerows(rows)
for folder, values in summary.items():
    print(folder, len(values[0]), 'mean', *[round(mean(v),4) for v in values], 'max', *[round(max(v),4) for v in values],
          'improved/same/worse', *[sum((b<a) if kind==0 else (b==a) if kind==1 else (b>a) for a,b in zip(*values)) for kind in [0,1,2]])
print(out)
