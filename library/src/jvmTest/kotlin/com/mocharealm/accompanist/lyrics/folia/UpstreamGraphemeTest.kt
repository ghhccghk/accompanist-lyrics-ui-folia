package com.mocharealm.accompanist.lyrics.folia

import com.mocharealm.accompanist.lyrics.core.model.SyncedLyrics
import com.mocharealm.accompanist.lyrics.core.model.karaoke.*
import com.mocharealm.accompanist.lyrics.folia.internal.model.normalize
import com.mocharealm.accompanist.lyrics.folia.internal.text.*
import java.io.File
import kotlin.test.*

class UpstreamGraphemeTest {
    private fun line(parts: List<Triple<String, Int, Int>>) = normalize(SyncedLyrics(listOf(
        KaraokeLine.MainKaraokeLine(parts.map { KaraokeSyllable(it.first, it.second, it.third) },
            null, KaraokeAlignment.Unspecified, parts.minOf { it.second }, parts.maxOf { it.third })
    ))).lines.single()

    @Test fun actualUpstreamGroupingAndGraphemeFixture() {
        val cases = mapOf(
            "word" to listOf(Triple("Amber", 1000, 2000)),
            "syllables" to listOf(Triple("hurri", 1000, 1400), Triple("cane", 1400, 2000)),
            "contraction" to listOf("It", "’", "s ", "light", "!").mapIndexed { i, text -> Triple(text, i * 1000, i * 1000 + 500) },
            "unicode" to listOf(Triple("á👩‍🚀", 4000, 5000)),
            "cjk" to listOf("世", "界", "。").mapIndexed { i, text -> Triple(text, i * 1000, i * 1000 + 500) },
            *mapOf(
                "mixedCjk" to listOf("世","界"," ","a","b"," ","灯","光","!"),
                "semanticSticky" to listOf("世","界","’","s ","light"),
                "leadingWhitespace" to listOf("  ","世","界"," ","abc","!"),
                "asciiStickyEdge" to listOf("We","'re"," ","ready","?","!")
            ).map { (id,texts)->id to texts.mapIndexed { i,t->Triple(t,i*1000,i*1000+500) } }.toTypedArray(),
        )
        val expected = File("../verification/classic-fixtures/graphemes.tsv").readLines().filterNot { it.startsWith("#") || it.isEmpty() }
        val actual = cases.flatMap { (id, parts) ->
            (if(id=="syllables") displayUnits(line(parts)) else displayWords(line(parts))).flatMapIndexed { index, word -> word.graphemes.map { timing ->
                listOf(id, index, word.text, word.startUs, word.endUs, word.text.substring(timing.begin, timing.end),
                    timing.startUs, timing.endUs).joinToString("\t")
            } }
        }
        assertEquals(expected, actual, "Oracle generated by pinned Folia functions, not Kotlin expectations")
    }

    @Test fun firstStrongDirectionMatchesPinnedSourceIncludingSupplementaryLetters() {
        File("../verification/classic-fixtures/direction.tsv").readLines().filterNot {it.startsWith("#")||it.isBlank()}.forEach {row->
            val c=row.split('\t');assertEquals(c[1]=="rtl",isRtlLyric(c[0]),row)
        }
    }

    @Test fun shapingJoinRetainsStickyEffectiveAndOriginalSourceTimelines() {
        // Sticky "It's" is evenly retimed by upstream; joining the following in-word
        // fragment for shaping must not silently replace that timeline with source timing.
        val parts=listOf(Triple("It",0,100),Triple("'",100,200),Triple("s",200,800),Triple("bright",900,1500))
        val raw=displayWords(line(parts));val shaped=displayUnits(line(parts)).single()
        assertEquals(2,raw.size)
        assertEquals(raw[0].graphemes[1].startUs,shaped.graphemes[1].startUs)
        assertEquals(50_000,shaped.sourceGraphemes[1].startUs)
        assertEquals(900_000,shaped.graphemes[4].startUs)
    }

    @Test fun shapingMergePreservesNonuniformSourceTimingAndWholeGraphemes() {
        val hurricane = displayUnits(line(listOf(Triple("hurri", 1000, 1400), Triple("cane", 1400, 2000)))).single()
        assertEquals(2, hurricane.fragments.size)
        assertEquals(1_400_000, hurricane.graphemes[5].startUs)
        assertEquals(1_550_000, hurricane.graphemes[5].endUs)
        val contraction = displayUnits(line(listOf(Triple("It", 0, 100), Triple("’", 100, 200), Triple("s ", 200, 800)))).single()
        assertEquals(3, contraction.fragments.size)
        assertEquals(100_000, contraction.sourceGraphemes[2].startUs)
        // Upstream sticky word includes the trailing space: 5 graphemes over 800ms.
        assertEquals(800_000 * 2 / 5, contraction.graphemes[2].startUs)
        val combined = displayUnits(line(listOf(Triple("a", 0, 100), Triple("́", 100, 200)))).single()
        assertEquals(listOf(TimedGrapheme(0, 2, 0, 200_000)), combined.graphemes)
        val arabic = displayUnits(line(listOf(Triple("مرحبا ", 0, 600), Triple("بالعالم", 1000, 1700))))
        assertEquals(2, arabic.size)
        assertEquals(1_000_000, arabic[1].graphemes[0].startUs)
    }
}
