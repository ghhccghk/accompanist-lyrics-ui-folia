import fs from 'node:fs';
import path from 'node:path';
import { referenceModules, revision, root } from './reference.mjs';

const { server, load } = await referenceModules();
try {
  const { buildWordGraphemeTimings } = await load('utils/lyrics/graphemeTiming.ts');
  const { buildPostLyricLayoutUnits, buildDisplayWordsFromLayoutUnits } = await load('utils/lyrics/cjkSemanticLayout.ts');
  const cases = [
    { id: 'word', words: [{ text: 'Amber', startTime: 1, endTime: 2 }] },
    { id: 'syllables', words: [{ text: 'hurricane', startTime: 1, endTime: 2,
      syllables: [{ text: 'hurri', startTime: 1, endTime: 1.4 }, { text: 'cane', startTime: 1.4, endTime: 2 }] }] },
    { id: 'contraction', words: ['It', '’', 's ', 'light', '!'].map((text, i) => ({ text, startTime: i, endTime: i + .5 })) },
    { id: 'unicode', words: [{ text: 'á👩‍🚀', startTime: 4, endTime: 5 }] },
    { id: 'cjk', words: ['世', '界', '。'].map((text, i) => ({ text, startTime: i, endTime: i + .5 })) },
    ...[
      ['mixedCjk', ['世','界',' ','a','b',' ','灯','光','!']],
      ['semanticSticky', ['世','界','’','s ','light']],
      ['leadingWhitespace', ['  ','世','界',' ','abc','!']],
      ['asciiStickyEdge', ['We',"'re",' ','ready','?','!']],
    ].map(([id,texts])=>({id,words:texts.map((text,i)=>({text,startTime:i,endTime:i+.5}))})),
  ];
  const lines = ['# generated by fixed upstream functions, revision=' + revision,
    '# case\twordIndex\ttext\tstartUs\tendUs\tgrapheme\tcharStartUs\tcharEndUs'];
  const json = [];
  for (const c of cases) {
    const line = { fullText: c.words.map(w => w.text).join(''), words: c.words };
    const units = buildPostLyricLayoutUnits(line, { semantic: true, sticky: true });
    const words = buildDisplayWordsFromLayoutUnits(units);
    json.push({ ...c, layoutUnits: units, displayWords: words, timings: words.map(w => buildWordGraphemeTimings(w)) });
    words.forEach((w, i) => buildWordGraphemeTimings(w).forEach(t => lines.push([
      c.id, i, w.text, Math.round(w.startTime * 1e6), Math.round(w.endTime * 1e6), t.char,
      Math.round(t.startTime * 1e6), Math.round(t.endTime * 1e6)].join('\t'))));
  }
  const output = path.join(root, 'verification/classic-fixtures');
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output, 'graphemes.tsv'), lines.join('\n') + '\n');
  fs.writeFileSync(path.join(output, 'grouping.json'), JSON.stringify({ revision, cases: json }, null, 2) + '\n');
  const {resolveLyricTextDirection}=await load('utils/lyrics/textDirection.ts');
  const directions=['123 مرحبا بالعالم','! שלום','123 𞤀 abc','abc مرحبا','世界 abc','123 !','مرحبا abc', 'á 123'];
  fs.writeFileSync(path.join(output,'direction.tsv'),['# original textDirection.ts '+revision,...directions.map(t=>t+'\t'+resolveLyricTextDirection(t))].join('\n')+'\n');
} finally { await server.close(); }
